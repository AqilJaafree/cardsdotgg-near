// Generates game/src/card_data.rs from shared/cards.json. Run: node near/scripts/gen-carddata.mjs
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../../", import.meta.url);
const { cards } = JSON.parse(readFileSync(new URL("shared/cards.json", root)));
for (const c of cards) if (c.hp + c.atk + c.def + c.spd !== 100) throw new Error(`${c.name} stats != 100`);
const stats = cards.map((c) => `    [${c.hp}, ${c.atk}, ${c.def}, ${c.spd}],`).join("\n");
const names = cards.map((c) => `    "${c.name}",`).join("\n");
const classes = cards.map((c) => `    "${c.assetClass}",`).join("\n");
writeFileSync(new URL("near/game/src/card_data.rs", root), `// GENERATED by near/scripts/gen-carddata.mjs from shared/cards.json. Do not edit.
pub const CARD_COUNT: usize = ${cards.length};

/// hp, atk, def, spd for each card id. Every row sums to 100.
pub const STATS: [[u8; 4]; ${cards.length}] = [
${stats}
];

pub const NAMES: [&str; ${cards.length}] = [
${names}
];

pub const CLASSES: [&str; ${cards.length}] = [
${classes}
];

pub fn stats(id: u8) -> (u8, u8, u8, u8) {
    let s = STATS[id as usize];
    (s[0], s[1], s[2], s[3])
}
`);
console.log("wrote", cards.length, "cards");
